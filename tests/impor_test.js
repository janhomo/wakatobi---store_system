const { makeEnv } = require('./gas_mock'); const vm = require('vm'), fs = require('fs'); const path = require('path');
const { env, ss } = makeEnv();
vm.runInContext(fs.readFileSync(path.join(__dirname, '../backend/ImporAwal.gs'), 'utf8'), env);
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../impor/data_awal.json'), 'utf8'));
const rows = n => ss.getSheetByName(n).data.slice(1).filter(r => r && r[0]);
const t = []; const ok = (n, c, x) => t.push((c ? 'PASS ' : 'FAIL ') + n + (c ? '' : '  -> ' + JSON.stringify(x)));
const PIN = ss.getSheetByName('Pengaturan').data.find(r => r && r[0] === 'PIN')[1];
const call = (b, tok) => JSON.parse(env.doPost({ postData: { contents: JSON.stringify(b) } }).getContent());
const TOKEN = call({ action: 'login', pin: PIN }).token;
env.imporAwal();
const J = rows('Jenis'), U = rows('Unit');
ok('98 units imported', U.length === 98, U.length);
ok('56 jenis', J.length === 56, J.length);
ok('codes unique and well-formed', new Set(U.map(r => r[0])).size === 98 && U.every(r => /^[A-Z]{3}-\d{3}$/.test(r[0])));
const bypre = {}; U.forEach(r => { const p = r[0].slice(0, 3); (bypre[p] = bypre[p] || []).push(+r[0].slice(4)); });
ok('codes sequential 1..n per prefix', Object.values(bypre).every(a => a.sort((x, y) => x - y).every((v, i) => v === i + 1)), bypre);
ok('LAS category added once', rows('Kategori').filter(r => r[1] === 'LAS').length === 1 && rows('Kategori').length === 10);
const jmap = Object.fromEntries(J.map(r => [r[0], r]));
ok('every unit points to a jenis', U.every(r => jmap[r[1]]));
const seen = new Set(); let dupNo = 0; U.forEach(r => { const k = r[1] + '#' + r[2]; if (seen.has(k)) dupNo++; seen.add(k); });
ok('unit numbers unique within each jenis', dupNo === 0, dupNo);
ok('no duplicate jenis (nama+merek+model)', new Set(J.map(r => [r[2], r[3], r[4]].join('|').toLowerCase())).size === J.length);
ok('jenis category prefix matches code prefix', U.every(r => { const k = rows('Kategori').find(x => x[0] === jmap[r[1]][1]); return k && k[1] === r[0].slice(0, 3); }));
ok('kondisi values valid', U.every(r => ['Normal', 'Servis', 'Rusak', 'Rusak total', 'Belum dicek'].includes(r[3])));
ok('tempat: 93 tanpa tempat (Gudang) + 5 di LOK-001 Gudang Karpenter', U.filter(r => r[4] === 'Gudang').length === 93 && U.filter(r => r[4] === 'LOK-001').length === 5 && rows('Tempat').length === 1 && rows('Tempat')[0][1] === 'Gudang Karpenter', rows('Tempat'));
const got = U.map(r => [jmap[r[1]][1], jmap[r[1]][2], jmap[r[1]][3], jmap[r[1]][4], Number(r[2]), r[3], r[4] === 'LOK-001' ? 'Gudang Karpenter' : r[4], r[8]].join('~')).sort();
const exp = data.map(d => [d[0], d[1], d[2], d[3], d[4], d[5], d[6], d[7]].join('~')).sort();
ok('sheet content equals source data row-for-row', JSON.stringify(got) === JSON.stringify(exp));
ok('Harga/Status empty, no Seri', U.every(r => !r[9] && !r[10] && !r[5]));
ok('log row written', rows('Log Perubahan').some(r => r[2] === 'Impor awal' && r[4] === 'Impor awal'));
const before = JSON.stringify(ss.getSheetByName('Unit').data);
env.imporAwal();
ok('second run refused, nothing changed', JSON.stringify(ss.getSheetByName('Unit').data) === before && rows('Jenis').length === 56);
const b = call({ action: 'bootstrap', token: TOKEN });
ok('bootstrap serves 56 jenis + 98 unit, no Harga', b.ok && b.jenis.length === 56 && b.unit.length === 98 && !JSON.stringify(b.unit).includes('Harga'));
const nm = U.filter(r => r[8]).length;
ok('notes kept (perlu dicek reasons)', nm === data.filter(d => d[7]).length && nm > 20, nm);
// setelah impor, fitur lain jalan: tambah unit ke jenis yang ada memberi nomor berikut
const bor = J.find(r => r[2] === 'Bor breaker kecil');
const add = call({ action: 'addUnit', token: TOKEN, oleh: 'Abidin', jenisId: bor[0], f: {} });
ok('addUnit after import: next unit number 5 and next free code', add.ok && /^BOR-\d{3}$/.test(add.kode) && rows('Unit').find(r => r[0] === add.kode)[2] === 5, add);
console.log(t.join('\n')); const f = t.filter(x => x.startsWith('FAIL')).length; console.log(f ? f + ' GAGAL' : 'SEMUA LULUS (' + t.length + ')'); process.exit(f ? 1 : 0);
